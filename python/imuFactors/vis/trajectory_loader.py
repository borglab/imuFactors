import numpy as np
import pandas as pd
import os
import glob
from dataclasses import dataclass
from typing import Optional, List, Tuple, Dict


# Default build folder
DEFAULT_BUILD_DIR = os.path.join(os.path.dirname(__file__), "../../../build")


@dataclass
class TrajectoryData:
    """Container for trajectory data loaded from CSV."""
    timestamp: np.ndarray
    # Ground truth (separate from predictions)
    gt_position: np.ndarray  # Nx3 array (x, y, z)
    gt_velocity: np.ndarray  # Nx3 array (vx, vy, vz)
    gt_rpy: np.ndarray      # Nx3 array (roll, pitch, yaw in degrees)
    gt_acceleration: Optional[np.ndarray] = None  # Nx3 array (ax, ay, az) if available
    # Predictions (separate from ground truth)
    pred_position: Optional[np.ndarray] = None  # Nx3 array
    pred_velocity: Optional[np.ndarray] = None  # Nx3 array
    pred_rpy: Optional[np.ndarray] = None      # Nx3 array
    pred_acceleration: Optional[np.ndarray] = None  # Nx3 array if available
    # Additional data
    covariance: Optional[np.ndarray] = None  # Nx9x9 array if available
    errors: Optional[np.ndarray] = None  # Nx9 array if available (err_x, err_y, etc.)
    
    @property
    def num_points(self) -> int:
        """Number of trajectory points."""
        return len(self.timestamp)
    
    @property
    def position(self) -> np.ndarray:
        """Legacy alias for ground truth position."""
        return self.gt_position
    
    @property
    def velocity(self) -> np.ndarray:
        """Legacy alias for ground truth velocity."""
        return self.gt_velocity
    
    @property
    def rpy(self) -> np.ndarray:
        """Legacy alias for ground truth orientation."""
        return self.gt_rpy


def compute_acceleration(velocity: np.ndarray, timestamp: np.ndarray) -> np.ndarray:
    """
    Compute acceleration from velocity using central differences.
    
    Args:
        velocity: Nx3 velocity array
        timestamp: N timestamp array
        
    Returns:
        (N-1)x3 acceleration array
    """
    if len(velocity) < 2:
        return np.array([])
    
    dt = np.diff(timestamp)
    accel = np.diff(velocity, axis=0) / dt[:, np.newaxis]
    return accel


def load_trajectory(filename: str, compute_accel: bool = False) -> Optional[TrajectoryData]:
    """
    Load trajectory from CSV file.
    
    Expected CSV columns (from TrajectoryValidator::exportToCSV):
        timestamp, gt_x, gt_y, gt_z, gt_vx, gt_vy, gt_vz, 
        gt_roll, gt_pitch, gt_yaw, pred_x, pred_y, pred_z, 
        pred_vx, pred_vy, pred_vz, pred_roll, pred_pitch, pred_yaw
    
    Args:
        filename: Path to CSV file
        compute_accel: Compute acceleration from velocity
        
    Returns:
        TrajectoryData object or None if loading fails
    """
    if not os.path.exists(filename):
        print(f"Warning: {filename} not found")
        return None
    
    try:
        df = pd.read_csv(filename)
        
        if df.empty:
            print(f"Warning: Empty file {filename}")
            return None
        
        # Extract ground truth
        gt_position = df[['gt_x', 'gt_y', 'gt_z']].values
        gt_velocity = df[['gt_vx', 'gt_vy', 'gt_vz']].values
        gt_rpy = df[['gt_roll', 'gt_pitch', 'gt_yaw']].values
        
        # Extract predictions
        pred_position = df[['pred_x', 'pred_y', 'pred_z']].values
        pred_velocity = df[['pred_vx', 'pred_vy', 'pred_vz']].values
        pred_rpy = df[['pred_roll', 'pred_pitch', 'pred_yaw']].values
        
        # Compute acceleration if requested
        gt_accel = compute_acceleration(gt_velocity, df['timestamp'].values) if compute_accel else None
        pred_accel = compute_acceleration(pred_velocity, df['timestamp'].values) if compute_accel else None
        
        return TrajectoryData(
            timestamp=df['timestamp'].values,
            gt_position=gt_position,
            gt_velocity=gt_velocity,
            gt_rpy=gt_rpy,
            gt_acceleration=gt_accel,
            pred_position=pred_position,
            pred_velocity=pred_velocity,
            pred_rpy=pred_rpy,
            pred_acceleration=pred_accel,
            covariance=None
        )
    except Exception as e:
        print(f"Error loading {filename}: {e}")
        return None


def load_nees_summary(filename: str = "nees_summary.csv") -> Optional[pd.DataFrame]:
    """
    Load NEES summary from CSV.
    
    Expected columns: dataset, best_nees, worst_nees, nees_ratio, 
                      best_alpha_gyro, best_alpha_acc, worst_alpha_gyro, worst_alpha_acc
    
    Args:
        filename: Path to NEES summary CSV
        
    Returns:
        DataFrame or None if not found
    """
    if not os.path.exists(filename):
        print(f"Warning: {filename} not found")
        return None
    
    try:
        return pd.read_csv(filename)
    except Exception as e:
        print(f"Error loading {filename}: {e}")
        return None


def discover_trajectories(
    filter_name: str,
    dataset_name: str,
    data_dir: str = "."
) -> dict:
    """
    Discover all trajectory files for a filter-dataset combination.
    
    Args:
        filter_name: Filter name (e.g., "gal3", "navstate")
        dataset_name: Dataset name (e.g., "MH01", "V202")
        data_dir: Directory containing CSV files
        
    Returns:
        Dict mapping interval suffix to file path
    """
    intervals = {
        '2s': f'{filter_name}_trajectory_{dataset_name}_2s.csv',
        '5s': f'{filter_name}_trajectory_{dataset_name}_5s.csv',
        '10s': f'{filter_name}_trajectory_{dataset_name}_10s.csv',
    }
    
    discovered = {}
    for suffix, filename in intervals.items():
        filepath = os.path.join(data_dir, filename)
        if os.path.exists(filepath):
            discovered[suffix] = filepath
    
    return discovered


def discover_datasets(data_dir: str = ".") -> List[str]:
    """
    Discover all datasets with ground truth files.
    
    Args:
        data_dir: Directory to search
        
    Returns:
        List of dataset names
    """
    gt_files = glob.glob(os.path.join(data_dir, "*_trajectory_*_2s.csv"))
    
    datasets = []
    for filename in gt_files:
        basename = os.path.basename(filename)
        # gal3_trajectory_MH01_2s.csv -> MH01
        parts = basename.split("_")
        if len(parts) >= 3:
            dataset = parts[2]
            if dataset not in datasets:
                datasets.append(dataset)
    
    return sorted(datasets)


def load_trajectory_from_build(
    filter_name: str,
    dataset_name: str,
    interval: str = "2s",
    build_dir: str = DEFAULT_BUILD_DIR,
    compute_accel: bool = False
) -> Optional[TrajectoryData]:
    """
    Load trajectory from build folder.
    
    Args:
        filter_name: Filter name (e.g., "gal3", "navstate")
        dataset_name: Dataset name (e.g., "MH01", "V202")
        interval: Time interval suffix (e.g., "2s", "5s", "10s")
        build_dir: Path to build directory
        compute_accel: Compute acceleration from velocity
        
    Returns:
        TrajectoryData object or None if not found
    """
    filename = f"{filter_name}_trajectory_{dataset_name}_{interval}.csv"
    filepath = os.path.join(build_dir, filename)
    return load_trajectory(filepath, compute_accel=compute_accel)


def load_best_worst_trajectories(
    dataset_name: str,
    filter_name: str = "gal3",
    build_dir: str = DEFAULT_BUILD_DIR
) -> Tuple[Optional[TrajectoryData], Optional[TrajectoryData]]:
    """
    Load best and worst noise calibration trajectories.
    
    Args:
        dataset_name: Dataset name (e.g., "MH01", "V202")
        filter_name: Filter name (default: "gal3")
        build_dir: Path to build directory
        
    Returns:
        Tuple of (best_trajectory, worst_trajectory)
    """
    best_file = os.path.join(build_dir, f"{filter_name}_trajectory_{dataset_name}_BEST_2s.csv")
    worst_file = os.path.join(build_dir, f"{filter_name}_trajectory_{dataset_name}_WORST_2s.csv")
    
    best = load_trajectory(best_file)
    worst = load_trajectory(worst_file)
    
    return best, worst


def discover_all_datasets(build_dir: str = DEFAULT_BUILD_DIR) -> Dict[str, List[str]]:
    """
    Discover all available datasets and intervals in build folder.
    
    Args:
        build_dir: Path to build directory
        
    Returns:
        Dict mapping filter_name to list of dataset names
    """
    result = {"gal3": [], "navstate": []}
    
    # Look for gal3 trajectories
    gal3_files = glob.glob(os.path.join(build_dir, "gal3_trajectory_*_2s.csv"))
    for f in gal3_files:
        basename = os.path.basename(f)
        # gal3_trajectory_MH01_2s.csv -> MH01
        parts = basename.replace("gal3_trajectory_", "").replace(".csv", "").split("_")
        if len(parts) >= 1:
            dataset = parts[0]
            if dataset not in result["gal3"]:
                result["gal3"].append(dataset)
    
    # Look for navstate trajectories
    navstate_files = glob.glob(os.path.join(build_dir, "navstate_trajectory_*_2s.csv"))
    for f in navstate_files:
        basename = os.path.basename(f)
        parts = basename.replace("navstate_trajectory_", "").replace(".csv", "").split("_")
        if len(parts) >= 1:
            dataset = parts[0]
            if dataset not in result["navstate"]:
                result["navstate"].append(dataset)
    
    # Sort datasets
    for key in result:
        result[key] = sorted(result[key])
    
    return result


def discover_intervals(
    dataset_name: str,
    filter_name: str = "gal3",
    build_dir: str = DEFAULT_BUILD_DIR
) -> List[str]:
    """
    Discover available intervals for a dataset.
    
    Args:
        dataset_name: Dataset name
        filter_name: Filter name
        build_dir: Path to build directory
        
    Returns:
        List of available intervals (e.g., ["2s", "5s", "10s"])
    """
    pattern = f"{filter_name}_trajectory_{dataset_name}_*.csv"
    files = glob.glob(os.path.join(build_dir, pattern))
    
    intervals = []
    for f in files:
        basename = os.path.basename(f)
        # gal3_trajectory_MH01_2s.csv -> 2s
        parts = basename.replace(f"{filter_name}_trajectory_{dataset_name}_", "").replace(".csv", "")
        if not parts.startswith("BEST") and not parts.startswith("WORST"):
            intervals.append(parts)
    
    return sorted(intervals)